"""Rebuild the commit tables from `git log`: the one in README.md and the one in the report
(report/commit_table.tex, included by report/main.tex).

    python scripts/commit_table.py                        # both tables up to HEAD
    python scripts/commit_table.py --freeze <commit>      # report table stops at the code-freeze commit
    python scripts/commit_table.py --check                # only say whether the tables are up to date

Afterwards recompile the report (cd report && latexmk -pdf main.tex) and commit README.md and report/.
A table cannot contain the commit that adds it, so the README table always ends one commit before the
commit that updated it; `git log --date=iso` shows that one and anything newer.
"""
import argparse
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
TEX = ROOT / "report" / "commit_table.tex"
HEADING = "## Commit history"


def git_log(until):
    """(full hash, date in IST, author, subject) for every commit up to `until`, oldest first."""
    out = subprocess.run(
        ["git", "log", "--reverse", "--date=format-local:%Y-%m-%d %H:%M", "--format=%H%x09%ad%x09%an%x09%s", until],
        cwd=ROOT, capture_output=True, text=True, check=True, env=dict(os.environ, TZ="Asia/Kolkata")).stdout
    return [line.split("\t", 3) for line in out.strip().splitlines()]


def readme_section(rows):
    md = lambda s: s.replace("|", "\\|")  # noqa: E731
    table = "\n".join(f"| {i} | `{h}` | {d} | {md(a)} | {md(m)} |" for i, (h, d, a, m) in enumerate(rows, 1))
    return (f"{HEADING}\n\n"
            "Every commit on `main`, oldest first (dates in IST), rebuilt with `python scripts/commit_table.py`.\n"
            "A table cannot list the commit that adds it, so `git log --date=iso` shows that one and anything newer.\n"
            "The report's commit table lists the commits up to the code freeze.\n\n"
            "| # | Commit | Date (IST) | Author | Message |\n|---|---|---|---|---|\n" + table + "\n\n")


def new_readme(rows):
    text = README.read_text()
    if HEADING not in text:
        return text.rstrip("\n") + "\n\n" + readme_section(rows)
    start = text.index(HEADING)
    nxt = text.find("\n## ", start + len(HEADING))
    end = len(text) if nxt < 0 else nxt + 1
    return text[:start] + readme_section(rows) + text[end:]


def tex_escape(s):
    for a, b in (("\\", r"\textbackslash{}"), ("_", r"\_"), ("&", r"\&"), ("%", r"\%"), ("#", r"\#"),
                 ("$", r"\$"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\^{}")):
        s = s.replace(a, b)
    return s


def tex_table(rows, panels):
    size = -(-len(rows) // panels)
    width = {1: "0.99", 2: "0.495", 3: "0.33"}[panels]
    parts = []
    for p in range(panels):
        chunk = rows[p * size:(p + 1) * size]
        body = "\n".join(f"{p * size + i + 1} & \\texttt{{{h[:10]}}} & {d} & {tex_escape(m)}\\\\"
                         for i, (h, d, _, m) in enumerate(chunk))
        parts.append(f"\\begin{{minipage}}[t]{{{width}\\textwidth}}\\centering\\scriptsize\n"
                     "\\begin{tabular}{@{}r@{\\hspace{4pt}}l@{\\hspace{4pt}}l@{\\hspace{4pt}}p{0.5\\linewidth}@{}}\\toprule\n"
                     "\\# & Commit & Date (IST) & Message\\\\\\midrule\n" + body +
                     "\n\\bottomrule\n\\end{tabular}\n\\end{minipage}")
    return ("% Generated by scripts/commit_table.py from git log. Do not edit by hand.\n"
            "\\begin{table*}[t]\\centering\n" + "\\hfill\n".join(parts) +
            "\n\\caption{Commit history of the repository up to the code freeze (branch \\texttt{main}; short hashes, "
            "dates in IST). Later commits are listed, with full hashes, in the README.}\\label{tab:commits}\n"
            "\\end{table*}\n")


def main():
    ap = argparse.ArgumentParser(description="Rebuild the commit tables in README.md and the report.")
    ap.add_argument("--freeze", default="HEAD", help="last commit for the report table (default: HEAD)")
    ap.add_argument("--panels", type=int, choices=(1, 2, 3), default=2, help="columns of the report table")
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if a table is out of date")
    a = ap.parse_args()

    readme, tex = new_readme(git_log("HEAD")), tex_table(git_log(a.freeze), a.panels)
    stale = [p.relative_to(ROOT) for p, new in ((README, readme), (TEX, tex))
             if not p.exists() or p.read_text() != new]
    if a.check:
        print("out of date: " + ", ".join(map(str, stale)) if stale else "commit tables are up to date")
        sys.exit(1 if stale else 0)
    README.write_text(readme)
    TEX.write_text(tex)
    print(f"README: {len(git_log('HEAD'))} commits; report: {len(git_log(a.freeze))} commits (up to {a.freeze})")


if __name__ == "__main__":
    main()
